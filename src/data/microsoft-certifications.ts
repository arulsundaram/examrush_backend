export const getCertificationByCode = (code: string): MicrosoftCertification | undefined => {
  return microsoftCertifications.find((cert) => cert.code === code);
};

export const getCertificationsByCategory = (category: string): MicrosoftCertification[] => {
  return microsoftCertifications.filter((cert) => cert.category === category);
};

